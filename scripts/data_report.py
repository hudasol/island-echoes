"""Write the generated tables of docs/DATA.md from the fact files and snapshots.

    python scripts/data_report.py           # rewrite the generated block in docs/DATA.md
    python scripts/data_report.py --check   # exit 1 if the block is out of date

Everything printed is counted from data/islands/*.json and data/snapshots/*/*.json. Nothing is typed by hand.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "DATA.md"
BEGIN, END = "<!-- data-report:begin -->", "<!-- data-report:end -->"


def build() -> str:
    islands = [json.loads(p.read_text(encoding="utf-8")) for p in sorted((ROOT / "data" / "islands").glob("*.json"))]
    facts = [(i["slug"], f) for i in islands for f in i["facts"]]
    conf = Counter(f["confidence"] for _, f in facts)
    wiki = [f for _, f in facts if "wikipedia.org" in urlparse(f["source_url"]).netloc]
    pubs = Counter(f["publisher"] for _, f in facts)
    cats = Counter(f["category"] for _, f in facts)
    dates = sorted(f["retrieved"] for _, f in facts)
    creatures = sum(len(i["creatures"]) for i in islands)
    urls = {f["source_url"] for _, f in facts}
    snaps = sorted((ROOT / "data" / "snapshots").glob("*/*.json"))
    stamps = sorted(json.loads(p.read_text(encoding="utf-8"))["fetched_at"][:10] for p in snaps)
    out = [BEGIN, "", "Generated by `python scripts/data_report.py` from the fact files and snapshots. Do not edit by hand.", ""]
    out += ["| Measure | Value |", "|---|---|",
            f"| Islands | {len(islands)} |", f"| Creatures | {creatures} |", f"| Facts | {len(facts)} |",
            f"| Distinct source URLs | {len(urls)} |", f"| Distinct web hosts | {len({urlparse(u).netloc for u in urls})} |", f"| Distinct publishers | {len(pubs)} |",
            f"| Facts retrieved between | {dates[0]} and {dates[-1]} |",
            f"| Facts citing Wikipedia | {len(wiki)} ({100 * len(wiki) / len(facts):.0f}%) |",
            f"| Confidence High / Medium / Low | {conf['high']} / {conf['medium']} / {conf['low']} |",
            f"| High confidence facts citing Wikipedia | {sum(1 for f in wiki if f['confidence'] == 'high')} |",
            f"| Snapshots (NASA POWER and GBIF) | {len(snaps)}, fetched {stamps[0]} to {stamps[-1]} |", ""]
    out += ["### Facts per island", "", "| Island | Facts | Creatures | Citing Wikipedia | High | Medium | Low |", "|---|---|---|---|---|---|---|"]
    for i in islands:
        c = Counter(f["confidence"] for f in i["facts"])
        w = sum("wikipedia.org" in f["source_url"] for f in i["facts"])
        out.append(f"| {i['name']} | {len(i['facts'])} | {len(i['creatures'])} | {w} | {c['high']} | {c['medium']} | {c['low']} |")
    out += ["", "### Facts per category", "", "| Category | Facts |", "|---|---|"] + [f"| {k} | {v} |" for k, v in sorted(cats.items())]
    out += ["", "### Facts per publisher (top 15)", "", "| Publisher | Facts |", "|---|---|"] + [f"| {k} | {v} |" for k, v in pubs.most_common(15)]
    out += ["", "### Facts that cite Wikipedia", "",
            "Each fact cites one source, so these rest on one encyclopedia page. The list is the work queue for replacement by a primary source; a fact is replaced only when a primary source fetched for the purpose states it.", "",
            "| ID | Confidence | Category |", "|---|---|---|"]
    out += [f"| {f['id']} | {f['confidence']} | {f['category']} |" for f in wiki]
    out += ["", END]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    block = build()
    text = DOC.read_text(encoding="utf-8")
    if BEGIN in text:
        new = re.sub(re.escape(BEGIN) + ".*?" + re.escape(END), lambda _m: block, text, flags=re.S)
    else:
        new = text.rstrip("\n") + "\n\n## Provenance report\n\n" + block + "\n"
    if args.check:
        return 0 if new == text else 1
    DOC.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
